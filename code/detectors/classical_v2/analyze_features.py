MATCH_DISTANCE = 7.0  # µm


def compute_roc_pr_auc(scores: np.ndarray, labels: np.ndarray):
    """Computes exact ROC-AUC and PR-AUC using pure NumPy."""
    if len(scores) == 0:
        return 0.5, 0.0

    desc_order = np.argsort(-scores)
    sorted_labels = labels[desc_order]

    n_pos = int(np.sum(sorted_labels == 1))
    n_neg = int(np.sum(sorted_labels == 0))

    if n_pos == 0 or n_neg == 0:
        return 0.5, 0.0

    tps = np.cumsum(sorted_labels == 1)
    fps = np.cumsum(sorted_labels == 0)

    tpr = tps / n_pos
    fpr = fps / n_neg
    prec = tps / (tps + fps)

    # ROC AUC: trapz with fpr on x-axis
    # prepend (0,0)
    fpr_roc = np.concatenate([[0.0], fpr])
    tpr_roc = np.concatenate([[0.0], tpr])
    roc_auc = float(np.trapz(tpr_roc, fpr_roc))

    # PR AUC: trapezoidal integration of precision over recall
    rec_pr = np.concatenate([[0.0], tpr])
    prec_pr = np.concatenate([[1.0], prec])
    pr_auc = float(np.trapz(prec_pr, rec_pr))

    return roc_auc, pr_auc


def extract_features_for_volume(dataset_name: str):
    """
    Extracts cheap features for all D2 detections in a single volume,
    matching each frame against ground truth.
    """
    zarr_path = os.path.join(TEST_DIR, f"{dataset_name}.zarr")
    geff_path = os.path.join(TRAIN_DIR, f"{dataset_name}.geff")

    gt_nodes, gt_edges, n_total = load_gt_geff(geff_path)
    gt_by_t = {}
    for gid, (t, z, y, x) in gt_nodes.items():
        gt_by_t.setdefault(t, []).append((gid, z, y, x))

    zg = zarr.open_group(zarr_path, mode="r")
    arr = zg["0"]
    num_t = arr.shape[0]

    # Nuclear ellipsoid mask offsets (radius Z=2, XY=5)
    rz, rxy = 2, 5
    zg_grid, yg_grid, xg_grid = np.ogrid[-rz:rz + 1, -rxy:rxy + 1, -rxy:rxy + 1]
    nuc_mask = ((zg_grid / rz)**2 + (yg_grid / rxy)**2 + (xg_grid / rxy)**2) <= 1.0
    cz_rel, cy_rel, cx_rel = np.nonzero(nuc_mask)
    cz_rel -= rz
    cy_rel -= rxy
    cx_rel -= rxy

    rows = []

    for t in range(num_t):
        raw_vol = arr[t][:]  # (64, 256, 256) uint16

        # Normalization identical to D2_LocalMax_LocalBG_P90
        v_norm_p = normalize_percentile(raw_vol, p_low=1.0, p_high=99.0)
        bg = ndi.uniform_filter(v_norm_p, size=(3, 21, 21))
        fg = np.maximum(0.0, v_norm_p - bg)
        fg_max = np.percentile(fg, 99.5)
        v_norm = np.clip(fg / fg_max, 0.0, 1.0) if fg_max > 0 else fg

        # Smoothed
        smoothed = ndi.gaussian_filter(v_norm, sigma=(1.2, 2.5, 2.5))
        thresh = np.percentile(smoothed, 90.0)

        # Local maxima
        max_filt = ndi.maximum_filter(smoothed, size=(2 * 2 + 1, 2 * 5 + 1, 2 * 5 + 1))
        peaks_mask = (smoothed == max_filt) & (smoothed > thresh)
        peak_coords = np.argwhere(peaks_mask)

        if len(peak_coords) == 0:
            continue

        # Match against GT at frame t
        glist = gt_by_t.get(t, [])
        is_matched_dict = {i: 0 for i in range(len(peak_coords))}
        dist_to_gt = np.full(len(peak_coords), 999.0, dtype=np.float64)

        if glist:
            p_ids = np.arange(len(peak_coords), dtype=np.int64)
            p_coords = peak_coords.astype(np.float64)
            g_ids = np.array([g[0] for g in glist], dtype=np.int64)
            g_coords = np.array([[g[1], g[2], g[3]] for g in glist], dtype=np.float64)

            p2g, _ = match_nodes_bipartite(p_coords, p_ids, g_coords, g_ids, scale=tuple(SCALE), max_distance=MATCH_DISTANCE)
            for p_idx in p2g:
                is_matched_dict[p_idx] = 1

            # Compute nearest GT distance for every peak
            p_phys = p_coords * SCALE
            g_phys = g_coords * SCALE
            all_dists = sp_dist.cdist(p_phys, g_phys)
            dist_to_gt = np.min(all_dists, axis=1)

        D, H, W = raw_vol.shape

        for i, (z0, y0, x0) in enumerate(peak_coords):
            # 1. Raw & Normalized Intensities
            raw_val = float(raw_vol[z0, y0, x0])
            norm_val = float(v_norm[z0, y0, x0])
            sm_val = float(smoothed[z0, y0, x0])
            bg_val = float(bg[z0, y0, x0])

            # 2. Local Signal-to-Background Ratio
            sbr_raw = raw_val / max(1.0, bg_val * 65535.0)
            sbr_norm = norm_val / max(1e-4, bg_val)

            # 3. 3D Laplacian (Curvature / Sharpness)
            if 0 < z0 < D - 1 and 0 < y0 < H - 1 and 0 < x0 < W - 1:
                # Physical second derivatives
                d2z = (float(v_norm[z0+1, y0, x0]) - 2*norm_val + float(v_norm[z0-1, y0, x0])) / (SCALE[0]**2)
                d2y = (float(v_norm[z0, y0+1, x0]) - 2*norm_val + float(v_norm[z0, y0-1, x0])) / (SCALE[1]**2)
                d2x = (float(v_norm[z0, y0, x0+1]) - 2*norm_val + float(v_norm[z0, y0, x0-1])) / (SCALE[2]**2)
                laplacian_phys = -(d2z + d2y + d2x)  # Positive for local maximum

                # Voxel second derivatives on smoothed
                sm_d2z = float(smoothed[z0+1, y0, x0]) - 2*sm_val + float(smoothed[z0-1, y0, x0])
                sm_d2y = float(smoothed[z0, y0+1, x0]) - 2*sm_val + float(smoothed[z0, y0-1, x0])
                sm_d2x = float(smoothed[z0, y0, x0+1]) - 2*sm_val + float(smoothed[z0, y0, x0-1])
                laplacian_sm = -(sm_d2z + sm_d2y + sm_d2x)

                # 3D Hessian on smoothed volume
                Hzz = sm_d2z
                Hyy = sm_d2y
                Hxx = sm_d2x
                Hzy = 0.25 * (float(smoothed[z0+1, y0+1, x0]) - float(smoothed[z0+1, y0-1, x0]) -
                              float(smoothed[z0-1, y0+1, x0]) + float(smoothed[z0-1, y0-1, x0]))
                Hzx = 0.25 * (float(smoothed[z0+1, y0, x0+1]) - float(smoothed[z0+1, y0, x0-1]) -
                              float(smoothed[z0-1, y0, x0+1]) + float(smoothed[z0-1, y0, x0-1]))
                Hyx = 0.25 * (float(smoothed[z0, y0+1, x0+1]) - float(smoothed[z0, y0+1, x0-1]) -
                              float(smoothed[z0, y0-1, x0+1]) + float(smoothed[z0, y0-1, x0-1]))

                H_mat = np.array([[Hzz, Hzy, Hzx], [Hzy, Hyy, Hyx], [Hzx, Hyx, Hxx]], dtype=np.float64)
                eigvals = np.linalg.eigvalsh(H_mat)  # Ascending order: e1 <= e2 <= e3
                e1, e2, e3 = float(eigvals[0]), float(eigvals[1]), float(eigvals[2])
                hess_det = float(np.linalg.det(H_mat))
                hess_norm = float(np.linalg.norm(H_mat, "fro"))
            else:
                laplacian_phys = 0.0
                laplacian_sm = 0.0
                e1, e2, e3 = 0.0, 0.0, 0.0
                hess_det = 0.0
                hess_norm = 0.0

            # 4. Local Contrast & Integrated Intensity
            z_min_b = max(0, z0 - rz)
            z_max_b = min(D, z0 + rz + 1)
            y_min_b = max(0, y0 - rxy)
            y_max_b = min(H, y0 + rxy + 1)
            x_min_b = max(0, x0 - rxy)
            x_max_b = min(W, x0 + rxy + 1)
            local_patch = v_norm[z_min_b:z_max_b, y_min_b:y_max_b, x_min_b:x_max_b]
            patch_min = float(np.min(local_patch))
            patch_mean = float(np.mean(local_patch))
            patch_std = float(np.std(local_patch))
            weber_contrast = (norm_val - patch_min) / max(1e-4, patch_mean)

            # Integrated intensity inside nuclear ellipsoid
            valid_z = (z0 + cz_rel >= 0) & (z0 + cz_rel < D)
            valid_y = (y0 + cy_rel >= 0) & (y0 + cy_rel < H)
            valid_x = (x0 + cx_rel >= 0) & (x0 + cx_rel < W)
            val_mask = valid_z & valid_y & valid_x
            nuc_vox_vals = v_norm[z0 + cz_rel[val_mask], y0 + cy_rel[val_mask], x0 + cx_rel[val_mask]]
            integrated_int = float(np.sum(nuc_vox_vals))

            rows.append({
                "dataset": dataset_name,
                "t": t,
                "z": z0,
                "y": y0,
                "x": x0,
                "is_match": is_matched_dict[i],
                "dist_to_gt_um": dist_to_gt[i],
                "raw_val": raw_val,
                "norm_val": norm_val,
                "smoothed_val": sm_val,
                "bg_val": bg_val,
                "sbr_raw": sbr_raw,
                "sbr_norm": sbr_norm,
                "laplacian_phys": laplacian_phys,
                "laplacian_sm": laplacian_sm,
                "hess_e1": e1,
                "hess_e2": e2,
                "hess_e3": e3,
                "hess_abs_e3": abs(e3),
                "hess_norm": hess_norm,
                "hess_det": hess_det,
                "patch_min": patch_min,
                "patch_mean": patch_mean,
                "patch_std": patch_std,
                "weber_contrast": weber_contrast,
                "integrated_int": integrated_int,
            })

    return rows


def analyze_feature_separability(df: pd.DataFrame):
    """
    Computes comparative statistics for each feature between True Matches (is_match=1)
    and False Detections (is_match=0).
    """
    features = [
        "smoothed_val",
        "norm_val",
        "raw_val",
        "sbr_norm",
        "sbr_raw",
        "laplacian_sm",
        "laplacian_phys",
        "hess_abs_e3",
        "hess_norm",
        "weber_contrast",
        "integrated_int",
        "patch_std",
    ]

    matched = df[df["is_match"] == 1]
    unmatched = df[df["is_match"] == 0]

    n_pos = len(matched)
    n_neg = len(unmatched)

    print(f"\nTotal Detections: {len(df):,}")
    print(f"True Matches (<= 7.0 µm from GT): {n_pos:,} ({n_pos / len(df) * 100:.2f}%)")
    print(f"False Detections (> 7.0 µm):        {n_neg:,} ({n_neg / len(df) * 100:.2f}%)")

    results = []
    labels = df["is_match"].values.astype(int)

    for feat in features:
        pos_vals = matched[feat].dropna().values
        neg_vals = unmatched[feat].dropna().values
        all_vals = df[feat].fillna(0.0).values

        pos_mean, pos_std = float(np.mean(pos_vals)), float(np.std(pos_vals))
        neg_mean, neg_std = float(np.mean(neg_vals)), float(np.std(neg_vals))
        pos_med = float(np.median(pos_vals))
        neg_med = float(np.median(neg_vals))

        # Cohen's d effect size
        pooled_std = np.sqrt(0.5 * (pos_std**2 + neg_std**2)) + 1e-8
        cohens_d = (pos_mean - neg_mean) / pooled_std

        # Kolmogorov-Smirnov 2-sample test
        ks_stat, ks_pval = ks_2samp(pos_vals, neg_vals)

        # ROC AUC & PR AUC
        roc_auc, pr_auc = compute_roc_pr_auc(all_vals, labels)
        # Invert score if negative correlation (e.g. if lower values = positive)
        if roc_auc < 0.5:
            inv_roc_auc, inv_pr_auc = compute_roc_pr_auc(-all_vals, labels)
            if inv_roc_auc > roc_auc:
                roc_auc, pr_auc = inv_roc_auc, inv_pr_auc
                cohens_d = -cohens_d

        results.append({
            "Feature": feat,
            "Matched Mean±Std": f"{pos_mean:.4f} ± {pos_std:.4f}",
            "Unmatched Mean±Std": f"{neg_mean:.4f} ± {neg_std:.4f}",
            "Matched Median": f"{pos_med:.4f}",
            "Unmatched Median": f"{neg_med:.4f}",
            "Cohen's d": round(cohens_d, 3),
            "KS Stat": round(ks_stat, 3),
            "ROC-AUC": round(roc_auc, 4),
            "PR-AUC": round(pr_auc, 4),
        })

    res_df = pd.DataFrame(results).sort_values(by="ROC-AUC", ascending=False)
    return res_df


def main():
    print("=" * 80)
    print("BIOHUB STEP 3: FEATURE ANALYSIS (TRUE MATCHES vs FALSE DETECTIONS)")
    print("=" * 80)

    from concurrent.futures import ProcessPoolExecutor
    t0 = time.time()
    all_rows = []
    print(f"Extracting features for 4 validation datasets in parallel: {VAL_DATASETS}...")
    with ProcessPoolExecutor(max_workers=4) as executor:
        results = list(executor.map(extract_features_for_volume, VAL_DATASETS))
        for r in results:
            all_rows.extend(r)

    df = pd.DataFrame(all_rows)
    csv_out = os.path.join(OUT_DIR, "detection_features.csv")
    df.to_csv(csv_out, index=False)
    print(f"\nSaved {len(df)} detection feature records to {csv_out} ({time.time() - t0:.1f}s)")

    summary_df = analyze_feature_separability(df)
    print("\n" + "=" * 80)
    print("FEATURE SEPARABILITY LEADERBOARD (SORTED BY ROC-AUC)")
    print("=" * 80)
    print(summary_df.to_string(index=False))

    summary_csv = os.path.join(OUT_DIR, "feature_separability_summary.csv")
    summary_df.to_csv(summary_csv, index=False)
    print(f"\nSaved summary to {summary_csv}")


if __name__ == "__main__":
    main()
